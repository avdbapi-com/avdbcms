import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { defineConfig, transformWithEsbuild, type Plugin } from 'vite';
import laravel from 'laravel-vite-plugin';
import preact from '@preact/preset-vite';

// Perf plan step 24: the layout's former inline theme CSS (see resources/views/components/layout.blade.php
// and App\Support\ThemeCss). Each file is its own entry so the layout can keep the old cascade order.
const themeCssInputs = {
    'layout-theme-a': 'resources/css/layout-theme-a.css',
    'layout-theme-b': 'resources/css/layout-theme-b.css',
};

// Theme collection v2: the token files generated by `php artisan avd:themes:build` (App\Support\ThemeTokens),
// one per theme (<id>.css) and one per other colour style (<id>/<flavor>.css). A page links only its theme's
// file and its colour style's file (App\Support\ThemeCss::themeTags). resources/css/themes/hero-decos (not a theme
// id: hyphenated) holds hero decoration sources that the build appends to their themes' files: no entry of its own.
const themeTokenDir = 'resources/css/themes';
const tokenFile = /^[a-z0-9_]+\.css$/;
const themeTokenInputs: Record<string, string> = Object.fromEntries(
    (fs.existsSync(themeTokenDir) ? fs.readdirSync(themeTokenDir, { withFileTypes: true }) : [])
        .flatMap((item): [string, string][] => {
            if (item.isFile() && tokenFile.test(item.name)) {
                return [[`theme-${item.name.slice(0, -4)}`, `${themeTokenDir}/${item.name}`]];
            }

            if (!item.isDirectory() || !/^[a-z0-9_]+$/.test(item.name)) {
                return [];
            }

            return fs.readdirSync(`${themeTokenDir}/${item.name}`)
                .filter((file) => tokenFile.test(file))
                .map((file): [string, string] => [`theme-${item.name}--${file.slice(0, -4)}`, `${themeTokenDir}/${item.name}/${file}`]);
        })
        .sort(([a], [b]) => a.localeCompare(b)),
);

// The admin shell's own document (WP6: resources/admin/admin.ts + admin.scss). Added only once the files
// exist, so a checkout without them still builds.
const adminInputs: Record<string, string> = Object.fromEntries(
    [
        ['admin', 'resources/admin/admin.ts'],
        ['admin-css', 'resources/admin/admin.scss'],
    ].filter(([, file]) => fs.existsSync(file)),
);

// Shipped exactly as written (whitespace and comments removed): see verbatimCss below.
const verbatimCssInputs = [...Object.values(themeCssInputs), ...Object.values(themeTokenInputs)];

/**
 * Ships the theme CSS exactly as written, only without whitespace and comments. The default CSS minify
 * (esbuild with the build target) would add -webkit- prefixes (e.g. -webkit-backdrop-filter, which Safari
 * before 18 obeys and the old inline CSS did not have) and rewrite colours (rgba(255, 255, 255, 0.92) ->
 * #ffffffeb, a slightly different alpha), so pages would no longer match the inline CSS they replace.
 *
 * Vite hashes the file name from its own minified CSS, not from what ships here, and /build/assets/* is
 * cached as immutable (browsers, panels, CDNs): an edit the default minify would absorb (such as adding
 * one of those -webkit- prefixes) must still get a new file name. So the CSS that Vite minifies and
 * hashes ends with a rule carrying a hash of the shipped bytes (a rule, because Vite's minify drops
 * comments; it never ships), and generateBundle refuses a build in which that hash did not reach the
 * hashed CSS.
 */
function verbatimCss(inputs: string[]): Plugin {
    const shipped = new Map<string, { code: string; hash: string }>();
    let root = process.cwd();

    return {
        name: 'avd-verbatim-css',
        apply: 'build',
        configResolved(config) {
            root = config.root;
        },
        async transform(code, id) {
            // Runs after vite:css (url() and @import handling) and before vite:css-post (minify, file name).
            const file = path.relative(root, id.split('?', 1)[0]).split(path.sep).join('/');

            if (!inputs.includes(file)) {
                return null;
            }

            const result = await transformWithEsbuild(code, file, {
                loader: 'css',
                minifyWhitespace: true,
                target: 'esnext',
                sourcemap: false,
            });

            // Vite fills in url()s of bundled files only after this point, in the CSS it minifies itself.
            if (/__VITE_(?:PUBLIC_)?ASSET__/.test(result.code)) {
                this.error(`avd-verbatim-css: ${file} has a url() to a bundled file, which this plugin cannot ship; use a data: URI or an absolute URL`);
            }

            const hash = createHash('sha256').update(result.code).digest('hex').slice(0, 16);
            shipped.set(file, { code: result.code, hash });

            // Appended at the end, so the existing code (and its source map) does not move.
            return { code: `${code}\n:root:not(:root){--avd-verbatim-css:"${hash}"}\n`, map: null };
        },
        generateBundle(_options, bundle) {
            for (const input of inputs) {
                const css = shipped.get(input);
                const asset = Object.values(bundle).find(
                    (output) => output.type === 'asset' && output.originalFileNames.includes(input),
                );

                if (css === undefined || asset === undefined || asset.type !== 'asset') {
                    this.error(`avd-verbatim-css: no CSS output for ${input}`);
                }

                if (typeof asset.source !== 'string' || !asset.source.includes(`"${css.hash}"`)) {
                    this.error(`avd-verbatim-css: the hashed CSS of ${input} lacks its content hash ${css.hash}, so its file name would not follow its content`);
                }

                asset.source = css.code;
            }
        },
    };
}

export default defineConfig({
    server: {
        host: '0.0.0.0',
        hmr: {
            host: 'localhost',
        },
    },
    experimental: {
        // Every URL the built files request at runtime is relative to the file that names it: the lazy
        // chunks' preloads in JS (resolved against the importing chunk's import.meta.url, as import()
        // itself is) and the font url()s in CSS (resolved against the stylesheet). So they follow the
        // URL the page loaded the build from: /build/... (document root = public/), /public/build/...
        // (root install with ASSET_URL=<origin>/public) or a CDN ASSET_URL. With the default base
        // '/build/' the preload helper requested /build/assets/X while import() loaded
        // /public/build/assets/X on root installs, so most chunks downloaded twice. The layout's Font
        // Awesome preload uses Vite::asset(), which is the URL the stylesheet resolves to.
        renderBuiltUrl(_filename, {hostType}) {
            return hostType === 'js' || hostType === 'css' ? {relative: true} : undefined;
        },
    },
    build: {
        outDir: 'public/build',
        manifest: 'manifest.json',
        rollupOptions: {
            input: {
                main: 'resources/js/app.ts',
                ...themeCssInputs,
                ...themeTokenInputs,
                ...adminInputs,
            },
            output: {
                manualChunks(id) {
                    const localeMatch = id.match(/resources[\\/]js[\\/]lang[\\/](ar|de|es|fr|hi|id|ja|ko|ms|pt|ru|th|tl|tr|vi|zh)\.ts$/);

                    if (localeMatch) {
                        return `locale-${localeMatch[1]}`;
                    }

                    if (id.includes('node_modules/react') ||
                        id.includes('node_modules/preact') ||
                        id.includes('node_modules/i18next') ||
                        id.includes('node_modules/@tanstack') ||
                        id.includes('node_modules/react-bootstrap') ||
                        id.includes('node_modules/react-i18next')) {
                        return 'vendor';
                    }
                },
            },
        },
        chunkSizeWarningLimit: 1600,
    },
    plugins: [
        laravel({
            input: ['resources/js/app.ts', ...Object.values(themeCssInputs), ...Object.values(themeTokenInputs), ...Object.values(adminInputs)],
            refresh: true,
        }),
        preact(),
        verbatimCss(verbatimCssInputs),
    ],
    css: {
        preprocessorOptions: {
            scss: {
                quietDeps: true,
                silenceDeprecations: ['import'],
            },
        },
    },
});
