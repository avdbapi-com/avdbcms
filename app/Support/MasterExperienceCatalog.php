    /**
     * @var array<string, array<string, mixed>>|null
     */
    protected static ?array $cachedAll = null;

    /**
     * The looks in gallery order. apply_settings holds every key a look writes (theme_preset, theme_flavor,
     * the colours, layouts and effect levels, active_master_experience).
     *
     * @return array<string, array{
     *     id: string,
     *     label: string,
     *     subtitle: string,
     *     best_for: string,
     *     icon: string,
     *     badge: string,
     *     badge_color: string,
     *     formerly: ?string,
     *     theme_name: string,
     *     phase: string,
     *     factory_default: bool,
     *     is_new: bool,
     *     theme: string,
     *     flavor: string,
     *     theme_preset: string,
     *     apply_settings: array<string, string>
     * }>
     */
    public static function all(): array
    {
        if (static::$cachedAll !== null) {
            return static::$cachedAll;
        }

        $legacy = static::upgradePolicy();
        $all = [];

        foreach (static::looks() as $id => $look) {
            $settings = $look['settings'];
            unset($look['settings']);

            $all[$id] = ['id' => $id] + $look + [
                'phase' => in_array($id, self::PHASE_A, true) ? 'A' : 'B',
                'factory_default' => $id === self::DEFAULT_ID,
                'is_new' => !isset($legacy[$id]),
                'theme' => $settings['theme_preset'],
                'flavor' => $settings['theme_flavor'],
                'theme_preset' => $settings['theme_preset'],
            ] + array_intersect_key($settings, array_flip(self::V1_KEYS)) + [
                'apply_settings' => $settings,
            ];
        }

        return static::$cachedAll = $all;
    }

    /**
     * The factory default look (demo1 parity).
     */
    public static function defaultPreset(): array
    {
        return static::all()[self::DEFAULT_ID];
    }

    /**
     * A look by its id or an old look id; null when unknown.
     */
    public static function find(string $id): ?array
    {
        $id = static::resolveId($id);

        return $id === null ? null : static::all()[$id];
    }

    /**
     * The current id of a look id or old look id; null when unknown.
     */
    public static function resolveId(string $id): ?string
    {
        $id = self::ALIASES[$id] ?? $id;

        return isset(static::all()[$id]) ? $id : null;
    }

    /**
     * Every setting a look writes, keyed by setting key; [] when the id is unknown.
     *
     * @return array<string, string>
     */
    public static function applySettings(string $id): array
    {
        return static::find($id)['apply_settings'] ?? [];
    }

    /**
     * What the v2 upgrade does with a site that still runs an untouched v1 look, keyed by the v1 look id
     * (theme_spec.json masters.upgrade_policy). alias is the 'theme/flavor' the look's old theme id maps to,
     * v2_theme the look's own. mode 'reapply': write the v2 look but keep the alias colour style (closest to
     * the old colours). mode 'colours_only' (the look moved to another theme): keep the stored layout keys,
     * take only the alias colours, clear active_master_experience and suggest the new look once.
     *
     * @return array<string, array{master: string, old_theme_preset: string, alias: string, v2_theme: string, mode: string, suggest: bool}>
     */
    public static function upgradePolicy(): array
    {
        $rows = [
            'netflix_cinema' => ['obsidian_gold', 'obsidian_gold/signature', 'pure_oled_black/signature', 'colours_only'],
            'youtube_spotlight_pro' => ['tokyo_neon', 'tokyo_neon/signature', 'tokyo_neon/signature', 'reapply'],
            'tiktok_shorts_hub' => ['sakura_blossom', 'fairy_floss/sakura', 'fairy_floss/signature', 'reapply'],
            'apple_bento_studio' => ['swiss_monolith', 'swiss_monolith/signature', 'swiss_monolith/signature', 'reapply'],
            'cyberpunk_hud' => ['cyber_matrix', 'cyber_matrix/signature', 'shibuya_rain/signature', 'colours_only'],
            'twitch_esports_live' => ['valorant_crimson', 'cyber_gladiator/signature', 'cyber_gladiator/signature', 'reapply'],
            'cosmic_astronomy_theater' => ['orion_nebula', 'interstellar/orion', 'interstellar/orion', 'reapply'],
            'luxury_imperial_salon' => ['royal_platinum', 'obsidian_gold/platinum', 'obsidian_gold/signature', 'reapply'],
        ];

        $policy = [];

        foreach ($rows as $master => [$oldThemePreset, $alias, $theme, $mode]) {
            $policy[$master] = [
                'master' => $master,
                'old_theme_preset' => $oldThemePreset,
                'alias' => $alias,
                'v2_theme' => $theme,
                'mode' => $mode,
                'suggest' => $mode === 'colours_only',
            ];
        }

        return $policy;
    }

